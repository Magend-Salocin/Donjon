	function RestaureParm($chaine){
		$MaChaine = null;
		$W = split(",,",$chaine);
		for($i=0;$i<sizeof($W);$i++){
		if($W[$i]!=null && $W[$i]!=""){
			$MaChaine .= "".$W[$i].",";
			}
		}
		$MaChaine .= "".$W[$i++]."";
		return $MaChaine;
	}
	
